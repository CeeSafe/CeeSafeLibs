#!/usr/bin/env python3
"""Writes src/tables.cee: Blowfish's initial P-array and S-boxes, which are the hexadecimal digits of pi's fraction
(Schneier 1993), computed here with Machin's formula rather than copied."""
import pathlib

WORDS = 18 + 4 * 256
BITS = WORDS * 32 + 64


def arctan_inv(x: int, one: int) -> int:
    total, term, n, sign = 0, one // x, 1, 1
    x2 = x * x
    while term:
        total += sign * (term // n)
        term //= x2
        n += 2
        sign = -sign
    return total


one = 1 << BITS
pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
fraction = pi - (3 << BITS)  # drop the integer part
words = []
for i in range(WORDS):
    shift = BITS - 32 * (i + 1)
    words.append((fraction >> shift) & 0xFFFFFFFF)
assert words[0] == 0x243F6A88 and words[1] == 0x85A308D3, "pi's first fraction words"

def table(name, values):
    lines = [f"const {name}: [u32; {len(values)}] = ["]
    for i in range(0, len(values), 6):
        lines.append("    " + " ".join(f"0x{v:08x}," for v in values[i : i + 6]))
    lines.append("];")
    return "\n".join(lines)

out = ["// Generated by tools/pi-tables.py: Blowfish's initial state, the hex digits of pi's fraction.", ""]
out.append(table("P_INIT", words[:18]))
out.append("")
out.append(table("S_INIT", words[18:]))
out.append("")
(pathlib.Path(__file__).resolve().parent.parent / "src" / "tables.cee").write_text("\n".join(out))
print("src/tables.cee: P", len(words[:18]), "S", len(words[18:]), "last", hex(words[-1]))
